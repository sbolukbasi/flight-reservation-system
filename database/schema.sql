CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(255) NOT NULL UNIQUE,
    password_hash varchar(255) NOT NULL,
    -- Account role used for authorization.
    -- New accounts default to USER.
    role varchar(20) NOT NULL default 'USER',
    -- Only USER and ADMIN roles are allowed.
    CONSTRAINT chk_users_role check ( role IN ('USER', 'ADMIN') )
);

CREATE TABLE passengers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    first_name varchar(100) NOT NULL,
    last_name varchar(100) NOT NULL,

    CONSTRAINT fk_passengers_users FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE airports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    iata_code varchar(3) NOT NULL UNIQUE,
    name varchar(100) NOT NULL,
    city varchar(100) NOT NULL,
    country varchar(100) NOT NULL,

    CONSTRAINT chk_iata_code check ( length(iata_code)=3 )
);

CREATE TABLE flights (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_number varchar(20) NOT NULL,
    departure_airport_id BIGINT NOT NULL,
    arrival_airport_id BIGINT NOT NULL,
    aircraft_model varchar(50) not null,
    departure_time timestamptz NOT NULL,
    arrival_time timestamptz NOT NULL,
    price decimal(10,2) NOT NULL,

    CONSTRAINT fk_flights_departure_airport FOREIGN KEY (departure_airport_id) REFERENCES airports(id),
    CONSTRAINT fk_flight_arrival_airport FOREIGN KEY (arrival_airport_id) REFERENCES airports(id),
    CONSTRAINT chk_flights_price check ( price >= 0 ),
    -- A flight cannot depart from and arrive at the same airport.
    CONSTRAINT chk_flight_airports_different check ( departure_airport_id != arrival_airport_id ),
    -- Arrival time must be later than departure time.
    CONSTRAINT chk_flight_arrivalTime_after_departureTime check ( arrival_time > departure_time ),
    -- The same flight number can be used at different departure times,
    -- but the same flight number and departure time combination must be unique.
    CONSTRAINT unq_flight_number_departure_time UNIQUE (flight_number, departure_time)
);

CREATE TABLE flight_seats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_id BIGINT NOT NULL,
    seat_number varchar(3) NOT NULL,

    CONSTRAINT fk_flight_seats_flights FOREIGN KEY (flight_id) REFERENCES flights(id),
    -- A seat number can appear only once within the same flight.
    -- The same seat number can exist on different flights.
    CONSTRAINT unq_flight_seat_number UNIQUE (flight_id, seat_number),
    -- Seat labels must contain 2 or 3 characters.
    CONSTRAINT chk_flight_seat_number_length check ( length(seat_number) BETWEEN 2 AND 3)
);

CREATE TABLE bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    passenger_id BIGINT NOT NULL,
    flight_seat_id BIGINT NOT NULL,
    -- Stores the ticket price at the time of booking.
    -- Preserves the original booking price if the flight's current price changes.
    booked_price decimal(10,2) NOT NULL,
    status varchar(20) NOT NULL default 'CONFIRMED',
    booking_time timestamptz NOT NULL default now(),

    CONSTRAINT fk_bookings_passenger FOREIGN KEY (passenger_id) REFERENCES passengers(id),
    CONSTRAINT fk_bookings_flight_seats FOREIGN KEY (flight_seat_id) REFERENCES flight_seats(id),
    CONSTRAINT chk_bookings_booked_price check ( booked_price>=0 ),
    -- Only the defined booking statuses are allowed.
    CONSTRAINT chk_bookings_status check ( status IN ('CONFIRMED', 'CANCELLED', 'COMPLETED'))
);

-- Prevents the same seat from having multiple bookings.
-- Cancelled bookings remain in the database as history and do not block rebooking.
CREATE UNIQUE INDEX unq_bookings_non_cancelled_flight_seat ON bookings(flight_seat_id) WHERE status != 'CANCELLED';